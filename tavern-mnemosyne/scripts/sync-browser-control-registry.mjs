import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  controlOperationRegistry,
} from '../src/control/control-operation-registry.js';

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const destination = path.join(
  packageRoot,
  'integrations',
  'sillytavern-extension',
  'control-operation-registry-browser.js',
);
const baseRegistry = controlOperationRegistry();
const evaluationRegistry = Object.fromEntries(
  Object.entries(controlOperationRegistry({
    includeEvaluation: true,
  })).filter(([operationId]) => operationId.startsWith('evaluation/')),
);
const generated = `// Generated by scripts/sync-browser-control-registry.mjs.
// The Node registry is authoritative; edit it and regenerate this file.

function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const child of Object.values(value)) deepFreeze(child);
    Object.freeze(value);
  }
  return value;
}

export const CONTROL_OPERATION_REGISTRY = deepFreeze(
  ${JSON.stringify(baseRegistry, null, 2)},
);

export const EVALUATION_CONTROL_OPERATION_REGISTRY = deepFreeze(
  ${JSON.stringify(evaluationRegistry, null, 2)},
);

export const ALL_CONTROL_OPERATION_REGISTRY = deepFreeze({
  ...CONTROL_OPERATION_REGISTRY,
  ...EVALUATION_CONTROL_OPERATION_REGISTRY,
});

export function controlOperationRegistry({
  includeEvaluation = false,
} = {}) {
  return includeEvaluation
    ? ALL_CONTROL_OPERATION_REGISTRY
    : CONTROL_OPERATION_REGISTRY;
}

function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map(key => [key, canonicalize(value[key])]),
    );
  }
  return value;
}

export function operationRegistryCanonicalJson(options) {
  return JSON.stringify(canonicalize(controlOperationRegistry(options)));
}
`;
await mkdir(path.dirname(destination), { recursive: true });
await writeFile(destination, generated, 'utf8');
process.stdout.write(`${destination}\n`);
